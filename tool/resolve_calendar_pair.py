"""Resolve the chronology and formatter pair against local core source.

Use while developing APIs that are newer than the published core packages.
Generated overrides are ignored by Git and are not release dependencies.
"""
import argparse
import hashlib
import os
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--chronology', type=Path, required=True)
parser.add_argument('--formatter', type=Path, required=True)
parser.add_argument('--replace-overrides', action='store_true',
                    help='Replace edited/non-generated overrides after reviewing their contents.')
args = parser.parse_args()
chronology, formatter = args.chronology.resolve(), args.formatter.resolve()
for root in [chronology, formatter]:
    if not (root / 'pubspec.yaml').is_file():
        raise SystemExit(f'Missing repository: {root}')

for package in [chronology / 'packages/general_datetime_core',
                formatter / 'packages/general_date_format_core']:
    if not (package / 'pubspec.yaml').is_file():
        raise SystemExit(f'Missing core package: {package}')

plans = {}

for directory in [formatter, formatter / 'example']:
    if not (directory / 'pubspec.yaml').is_file():
        continue
    # Relative paths support neighboring checkouts and CI's nested checkout.
    paths = {
        'general_datetime': chronology,
        'general_datetime_core': chronology / 'packages/general_datetime_core',
        'general_date_format_core': formatter / 'packages/general_date_format_core',
    }
    content = 'dependency_overrides:\n'
    for name, target in paths.items():
        path = Path(os.path.relpath(target, directory)).as_posix().replace("'", "''")
        content += f"  {name}:\n    path: '{path}'\n"
    plans[directory / 'pubspec_overrides.yaml'] = content

directory = formatter / 'packages/general_date_format_core'
path = Path(os.path.relpath(chronology / 'packages/general_datetime_core', directory)).as_posix().replace("'", "''")
plans[directory / 'pubspec_overrides.yaml'] = (
    f"dependency_overrides:\n  general_datetime_core:\n    path: '{path}'\n")

marker = '# Generated by resolve_calendar_pair.py; body-sha256='
updates = {}
for destination, body in plans.items():
    content = marker + hashlib.sha256(body.encode('utf-8')).hexdigest() + '\n' + body
    if destination.exists():
        previous = destination.read_text(encoding='utf-8')
        if previous == content:
            continue
        # Recognize the previous helper's identical output, or an untouched
        # generated file. Preserve developer edits and unrelated overrides.
        generated = False
        first, separator, remainder = previous.partition('\n')
        if first.startswith(marker) and separator:
            generated = first[len(marker):] == hashlib.sha256(
                remainder.encode('utf-8')).hexdigest()
        if previous != body and not generated and not args.replace_overrides:
            raise SystemExit(
                f'Preserving edited overrides: {destination}\n'
                'Review the file and merge the local paths, or explicitly use '
                '--replace-overrides. No override files were changed.')
    updates[destination] = content

for destination, content in updates.items():
    destination.write_text(content, encoding='utf-8')

print(f'Chronology wrapper: {chronology}\nFormatter: {formatter}')
